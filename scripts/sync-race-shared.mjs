#!/usr/bin/env node
/**
 * Copies the pure race modules into the `test-season` server function so the
 * server resolves races with exactly the code the browser replays.
 *
 *   npm run sync:server
 *
 * Run it after changing src/race/simulation.ts, testSeason.ts or callNames.ts
 * (the build runs it too). Output lives in supabase/functions/test-season/race/.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src/race');
const out = join(root, 'supabase/functions/test-season/race');
const HEADER = '// GENERATED by scripts/sync-race-shared.mjs from src/race — do not edit here.\n';

mkdirSync(out, { recursive: true });

for (const file of ['simulation', 'testSeason', 'callNames']) {
  const code = readFileSync(join(src, `${file}.ts`), 'utf8')
    // Deno needs explicit extensions on relative imports.
    .replace(/from '\.\/(\w+)'/g, "from './$1.ts'");
  writeFileSync(join(out, `${file}.ts`), HEADER + code);
}

// The server only needs the BodyColor type from sprites.ts, not its browser helpers.
writeFileSync(join(out, 'sprites.ts'), `${HEADER}export type BodyColor = string;\n`);

// Body colour per collection token (index entries are [Body, Weather, Speed, Burst, Endurance]).
const index = JSON.parse(readFileSync(join(src, 'token-index.json'), 'utf8'));
const bodies = Object.fromEntries(Object.entries(index).map(([id, e]) => [id, e[0]]));
writeFileSync(
  join(out, 'tokenBodies.ts'),
  `${HEADER}const BODIES: Record<string, string> = ${JSON.stringify(bodies)};\n\n` +
  'export function bodyOfToken(tokenId: number): string | null {\n  return BODIES[String(tokenId)] ?? null;\n}\n',
);

console.log(`Synced race modules → ${out.replace(root + '/', '')}`);
